def write_file(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def generate(schema_path, output_dir, docs=False):
    with open(schema_path) as f:
        schema = json.load(f)

    expected = "3"
    actual = schema.get("header", {}).get("schema_version")
    if actual != expected:
        raise Exception(
            "tempo_schema.json is schema_version {!r}, but this generator reads {!r}. Regenerate "
            "the schema, or use the generator that shipped with it.".format(actual, expected))

    generator = Generator(schema, docs)
    include = os.path.join(output_dir, "include")
    src = os.path.join(output_dir, "src")

    enums_h, enums_cc = generator.emit_enums()
    write_file(os.path.join(include, "tempo/reflected/enums.h"), enums_h)
    write_file(os.path.join(src, "enums.cc"), enums_cc)

    structs_fwd, structs_h, structs_cc = generator.emit_structs()
    write_file(os.path.join(include, "tempo/reflected/structs_fwd.h"), structs_fwd)
    write_file(os.path.join(include, "tempo/reflected/structs.h"), structs_h)
    write_file(os.path.join(src, "structs.cc"), structs_cc)

    write_file(os.path.join(include, "tempo/reflected/hierarchy.h"), HIERARCHY_H)
    write_file(os.path.join(src, "hierarchy.cc"), generator.emit_hierarchy())

    headers, sources = generator.emit_classes()
    for path, text in headers.items():
        write_file(os.path.join(include, path), text)
    for path, text in sources.items():
        write_file(os.path.join(src, path), text)

    mounts = generator.emit_assets()
    for mount, text in mounts.items():
        write_file(os.path.join(include, "tempo/reflected/assets", mount + ".h"), text)
    if mounts:
        write_file(os.path.join(include, "tempo/reflected/assets.h"), "\n".join(
            [GENERATED, "", "#pragma once", ""]
            + ['#include "tempo/reflected/assets/{}.h"'.format(m) for m in sorted(mounts)]) + "\n")

    write_file(os.path.join(output_dir, "CMakeLists.txt"), CMAKELISTS)
    return generator.stats, generator.by_module


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    stats, modules = generate(argv[1], argv[2], "--docs" in argv)
    print("modules            {}".format(len(modules)))
    print("classes            {}".format(stats["classes"]))
    print("structs / enums    {} / {} ({} passable as values, {} value fields omitted)".format(
        stats["structs"], stats["enums"], stats["struct_values"],
        stats["struct_value_fields_omitted"]))
    print("properties         {} ({} writable, {} read-only, {} struct-valued)".format(
        stats["properties"], stats["writable"], stats["read_only"], stats["struct_properties"]))
    print("functions          {} ({} with out parameters, {} out params dropped)".format(
        stats["functions"], stats["functions_with_out_params"], stats["out_params_dropped"]))
    print("components         {} ({} omitted)".format(
        stats["components"], stats["components_omitted"]))
    print("struct members     {} ({} omitted)".format(
        stats["struct_members"], stats["struct_members_omitted"]))
    print("omitted            {} properties, {} functions".format(
        stats["properties_omitted"], stats["functions_omitted"]))
    print("assets             {} ({} left out colliding)".format(
        stats["assets"], stats["assets_colliding"]))
    print("unnameable setters {} (property demoted to read-only)".format(
        stats["setters_unresolvable"]))
    print("name taken already {} properties, {} functions, {} components".format(
        stats["properties_shadowed"], stats["functions_shadowed"], stats["components_shadowed"]))
