"""Generate typed C++ classes from tempo_schema.json, for the C++ client's libtempo_reflected.

    gen_cpp_classes.py <schema.json> <output-dir> [--docs]

Writes `<output-dir>/include/tempo/reflected/...` (the headers a scenario includes),
`<output-dir>/src/...` (the definitions, compiled into libtempo_reflected) and
`<output-dir>/CMakeLists.txt` (which compiles them, given TEMPO_API_DIR and TEMPO_GRPC_DIR).
build_cpp_classes.py does both of the last steps and installs the result into the C++ client.

The C++ sibling of gen_rust_classes.py, off the same schema, with the same names -- the C++ client
mirrors the Rust one (TYPED_WORLD_API_PLAN.md §23). Where Rust needs a chain of Deref and an unsafe
upcast to model Unreal's single inheritance, C++ has inheritance: `class Pawn : public Actor`. One
tree, describing the project's whole build, because the C++ client is built per project rather than
published (§23.2).

Thousands of classes cannot be one header, so there is one per class, which includes its superclass
and forward-declares everything else it names; a header per module includes all of that module's
classes. Definitions are out of line, so including a module costs what its declarations cost.
"""

import json
import os
import re
import sys

from collections import defaultdict

from gen_classes_common import enumerator_members, resolve_setters, snake_case

GENERATED = "// Generated by gen_cpp_classes.py from tempo_schema.json. Do not edit."
RUNTIME = "::tempo::unreal"
RESULT = "::tempo::Result"
ROOT = "::tempo::reflected"

# C++'s keywords and alternative tokens, and the lowercase names a common platform header defines
# as a macro -- a member called `major` meets glibc's <sys/sysmacros.h>, one called `small` meets
# Windows' <rpcndr.h> -- since a macro rewrites an identifier before the compiler sees it.
RESERVED = frozenset("""
alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t
char32_t class compl concept const consteval constexpr constinit const_cast continue co_await
co_return co_yield decltype default delete do double dynamic_cast else enum explicit export extern
false float for friend goto if inline int long mutable namespace new noexcept not not_eq nullptr
operator or or_eq private protected public register reinterpret_cast requires return short signed
sizeof static static_assert static_cast struct switch template this thread_local throw true try
typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq
assert errno major minor stdin stdout stderr unix linux check verify require min max small near far
interface
""".split())

# Upper-case names a platform header defines as a macro, which an enumerator or an asset can be
# called: `ERROR` (wingdi.h), `DELETE` (winnt.h), `IN` and `OUT` (minwindef.h), and C's own.
MACROS = frozenset("""
TRUE FALSE NULL EOF ERROR DELETE IN OUT OPTIONAL CONST VOID DOMAIN OVERFLOW UNDERFLOW TRANSPARENT
OPAQUE ABSOLUTE RELATIVE ALTERNATE WINDING CALLBACK STRICT NEAR FAR PASCAL INFINITE BOOL CHAR INT
""".split())

# The names the runtime's Handle declares, which a member must not hide.
HANDLE_MEMBERS = frozenset(("object", "is_a", "hierarchy", "kPath", "object_"))

# Names under tempo/reflected/ that are the generator's own, which a module cannot also be called.
FIXED_NAMES = frozenset(("classes", "enums", "structs", "structs_fwd", "hierarchy", "assets"))

# Kinds that map straight onto a C++ type.
SIMPLE_TYPES = {
    "bool": "bool",
    "int": "::std::int32_t",
    "int64": "::std::int64_t",
    # Unreal's float and double properties both travel in float_value. The typed surface says
    # double for both, because that is what Unreal stores; the narrowing is the wire's.
    "float": "double",
    "double": "double",
    "string": "::std::string",
    "vector": RUNTIME + "::UnrealVector",
    "vector2d": RUNTIME + "::UnrealVector2D",
    "intvector": RUNTIME + "::UnrealIntVector",
    "intpoint": RUNTIME + "::UnrealIntPoint",
    "rotator": RUNTIME + "::UnrealRotator",
    "quat": RUNTIME + "::UnrealQuat",
    "transform": RUNTIME + "::UnrealTransform",
    "color": RUNTIME + "::UnrealColor",
    "class": RUNTIME + "::ClassRef",
}

# Passed by value rather than by const reference.
BY_VALUE = frozenset(("bool", "::std::int32_t", "::std::int64_t", "double"))

# Element kinds a container has a Value variant for. Anything else makes its container
# nested-access-only, which the server already reports as value_expressible: false.
CONTAINER_ELEMENTS = frozenset(
    ("bool", "int", "int64", "float", "double", "string", "enum", "class", "asset", "actor",
     "component"))

# How each kind is read and written. PLAIN goes through ValueTraits both ways, which in C++ covers
# enums, assets, struct values and containers of all of them. A reference names an actor or a
# component, and which one cannot be told from the handle, so OBJECT and OBJECTS are written through
# helpers that say.
PLAIN, OBJECT, OBJECTS = range(3)


class Unsupported(Exception):
    """A type the API cannot carry. Its member is omitted rather than loosely typed."""


def cpp_str(text):
    """A C++ string literal.

    Everything outside printable ASCII is escaped as octal bytes of its UTF-8 encoding: MSVC reads a
    source file in the system code page unless told otherwise, and Blueprint function names do
    contain emoji. Octal rather than hex, because a hex escape runs on through any hex digits that
    follow it.
    """
    escaped = []
    for character in str(text):
        if character in ('"', "\\"):
            escaped.append("\\" + character)
        elif 0x20 <= ord(character) < 0x7F:
            escaped.append(character)
        else:
            escaped.extend("\\{:03o}".format(byte) for byte in character.encode("utf-8"))
    return '"' + "".join(escaped) + '"'


def ident(text):
    """One name as a legal C++ identifier."""
    cleaned = re.sub(r"\W", "_", text)
    if not cleaned or cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned + "_" if cleaned in RESERVED or cleaned in MACROS else cleaned


def snake(name):
    """An Unreal member name as C++ spells it: the Rust client's name, legal here."""
    return snake_case(name, RESERVED)


def module_for(package):
    """The namespace path a class's package maps to, as a list of segments -- Rust's modules."""
    if package.startswith("/Script/"):
        return [snake(package[len("/Script/"):])]
    segments = [snake(s) for s in package.strip("/").split("/")]
    return segments[:-1] if len(segments) > 1 else segments


def doc_comment(text, indent):
    """A tooltip as `///` lines. A line ending in a backslash would splice the next line -- the
    declaration -- into the comment, so the backslash goes."""
    return ["{}/// {}".format(indent, line.strip().rstrip("\\").rstrip())
            for line in (text or "").strip().splitlines() if line.strip()]


class Generator:
    def __init__(self, schema, docs=False):
        self.schema = schema
        self.docs = docs
        self.classes_by_path = {c["path"]: c for c in schema["classes"]}
        self.struct_names = {s["name"] for s in schema.get("structs", [])}
        self.structs_by_name = {s["name"]: s for s in schema.get("structs", [])}
        # The classifier's answer, recorded per struct by the walk -- not worked out again here.
        self.expressible_structs = {s["name"] for s in schema.get("structs", [])
                                    if s.get("value_expressible")}
        self.enum_names = {e["name"] for e in schema.get("enums", [])}
        self.by_module = defaultdict(list)
        for cls in schema["classes"]:
            self.by_module[tuple(module_for(cls["package"]))].append(cls)
        for segments in self.by_module:
            if segments[0] in FIXED_NAMES:
                raise Exception("module {} is named like one of the generator's own headers ({}); "
                                "it would overwrite it".format("::".join(segments), segments[0]))
        self.stats = defaultdict(int)
        # Before anything is emitted, so the accessors here and in the other clients agree about
        # which properties are writable.
        self.stats["setters_unresolvable"] = resolve_setters(schema)

    # -- type rendering -------------------------------------------------------------------------

    def cpp_type(self, type_desc, references):
        """The C++ type for one schema type, and how the runtime carries it.

        `references` collects the classes the type names, so the header can forward-declare them
        and the definitions can include them.
        """
        kind = type_desc.get("kind")

        if kind in SIMPLE_TYPES:
            return SIMPLE_TYPES[kind], PLAIN

        if kind == "enum":
            name = type_desc.get("enum")
            if not name or name not in self.enum_names:
                raise Unsupported("enum not in the schema")
            return ROOT + "::enums::" + ident(name), PLAIN

        if kind in ("actor", "component"):
            return self.class_type(type_desc, references), OBJECT

        if kind == "asset":
            referenced = self.classes_by_path.get(type_desc.get("class", ""))
            if referenced is None:
                # Its class is outside this walk, so the most that can be said is that it is an asset.
                return RUNTIME + "::AssetRef<>", PLAIN
            references.add(referenced["path"])
            return "{}::AssetRef<{}>".format(RUNTIME, self.path_of(referenced)), PLAIN

        if kind == "struct":
            name = type_desc.get("struct") or ""
            if name not in self.expressible_structs:
                # Reachable a member at a time through its proxy, never as one value.
                raise Unsupported("struct {!r} cannot travel as one value".format(name))
            return ROOT + "::structs::" + ident(name), PLAIN

        if kind in ("array", "set"):
            element = type_desc.get("element") or {}
            element_kind = element.get("kind")
            if element_kind == "struct":
                # Arrays only: a set of structs has no Value variant.
                if kind != "array":
                    raise Unsupported("a set of structs has no Value variant")
                inner, _ = self.cpp_type(element, references)
                return "::std::vector<{}>".format(inner), PLAIN
            if element_kind not in CONTAINER_ELEMENTS:
                raise Unsupported("no Value variant for a container of {!r}".format(element_kind))
            inner, how = self.cpp_type(element, references)
            return "::std::vector<{}>".format(inner), OBJECTS if how == OBJECT else PLAIN

        raise Unsupported(type_desc.get("unsupported_reason") or "kind {!r}".format(kind))

    def class_type(self, type_desc, references):
        referenced = self.classes_by_path.get(type_desc.get("class", ""))
        if referenced is None:
            # The pointee is outside this walk, so there is no generated type to name.
            raise Unsupported("the referenced class is not in this build")
        references.add(referenced["path"])
        return self.path_of(referenced)

    def path_of(self, cls):
        return "{}::classes::{}::{}".format(ROOT, "::".join(module_for(cls["package"])),
                                            ident(cls["name"]))

    def header_of(self, cls):
        """The include path of a class's own header."""
        return "tempo/reflected/classes/{}/{}.h".format("/".join(module_for(cls["package"])),
                                                         ident(cls["name"]))

    @staticmethod
    def parameter(cpp):
        return cpp if cpp in BY_VALUE or cpp.startswith(ROOT + "::enums::") else "const {}&".format(cpp)

    def docs_for(self, member, indent):
        return doc_comment(member.get("tooltip"), indent) if self.docs else []

    # -- members --------------------------------------------------------------------------------

    def emit_property(self, member, name, used, references):
        """The accessors for one property, as (declarations, definitions)."""
        try:
            cpp, how = self.cpp_type(member, references)
        except Unsupported:
            self.stats["properties_omitted"] += 1
            return [], []

        getter = snake(member["name"])
        if getter in used:
            self.stats["properties_shadowed"] += 1
            return [], []
        used.add(getter)
        used.add("watch_" + getter)
        if member.get("writable"):
            # Reserved so a Set<Name> function cannot take the setter's name out from under it.
            # Only for a writable property: a read-only one has no setter to protect, and its
            # Set<Name> function is then the one way to change it.
            used.add("set_" + getter)

        literal = cpp_str(member["name"])
        declarations = self.docs_for(member, "\t")
        definitions = []
        self.stats["properties"] += 1

        declarations.append("\t{}<{}> {}() const;".format(RESULT, cpp, getter))
        # A BlueprintGetter is called rather than read through, because it may be the only thing
        # that computes the value.
        accessor = member.get("getter") or ""
        read = "object_.get_via<{}>({})".format(cpp, cpp_str(accessor)) if accessor and how == PLAIN \
            else "object_.get<{}>({})".format(cpp, literal)
        definitions.append("{}<{}> {}::{}() const {{ return {}; }}".format(
            RESULT, cpp, name, getter, read))

        if how == PLAIN:
            # Streaming is a plain read repeated, so only the plainly-carried kinds offer it.
            stream = "{}<{}::PropertyStream<{}>>".format(RESULT, RUNTIME, cpp)
            declarations.append("\t{} watch_{}() const;".format(stream, getter))
            definitions.append("{} {}::watch_{}() const {{ return object_.watch<{}>({}); }}".format(
                stream, name, getter, cpp, literal))

        if not member.get("writable"):
            # Readable but not writable: no setter at all, so writing one is a compile error that
            # names the method.
            self.stats["read_only"] += 1
            return declarations, definitions

        self.stats["writable"] += 1
        declarations.append("\t{}<void> set_{}({} value) const;".format(
            RESULT, getter, self.parameter(cpp)))
        setter = member.get("setter") or ""
        if setter and how == PLAIN:
            # Both the function and what it calls its argument: CallFunction rejects an unnamed
            # argument and matches the name against the function's own parameters.
            body = "return object_.set_via({}, {}, value);".format(
                cpp_str(setter), cpp_str(member.get("setter_argument", "")))
        elif how == PLAIN:
            body = "return object_.set({}, value);".format(literal)
        elif how == OBJECT:
            body = "return object_.set_{}_ref({}, value.object());".format(
                "actor" if member.get("kind") == "actor" else "component", literal)
        else:
            element = (member.get("element") or {}).get("kind")
            body = ("::std::vector<{}::ObjectRef> objects; for (const auto& v : value) "
                    "objects.push_back(v.object()); return object_.set_{}_refs({}, objects);").format(
                        RUNTIME, "actor" if element == "actor" else "component", literal)
        definitions.append("{}<void> {}::set_{}({} value) const {{ {} }}".format(
            RESULT, name, getter, self.parameter(cpp), body))
        return declarations, definitions

    def emit_struct_property(self, member, name, used):
        """A struct-valued property: a typed proxy to reach into, and a setter when it travels whole."""
        struct = member.get("struct") or ""
        if struct not in self.struct_names:
            self.stats["properties_omitted"] += 1
            return [], []
        accessor = snake(member["name"])
        if accessor in used:
            self.stats["properties_shadowed"] += 1
            return [], []
        used.add(accessor)
        self.stats["struct_properties"] += 1
        proxy = "{}::structs::{}Ref".format(ROOT, ident(struct))
        literal = cpp_str(member["name"])
        declarations = self.docs_for(member, "\t") + ["\t{} {}() const;".format(proxy, accessor)]
        definitions = ["{} {}::{}() const {{ return {}(object_.struct_ref({})); }}".format(
            proxy, name, accessor, proxy, literal)]
        if not member.get("writable") or struct not in self.expressible_structs:
            return declarations, definitions

        setter_name = "set_" + accessor
        if setter_name in used:
            return declarations, definitions
        used.add(setter_name)
        value = "{}::structs::{}".format(ROOT, ident(struct))
        setter = member.get("setter") or ""
        body = "return object_.set_via({}, {}, value);".format(
            cpp_str(setter), cpp_str(member.get("setter_argument", ""))) if setter \
            else "return object_.set({}, value);".format(literal)
        declarations.append("\t{}<void> {}(const {}& value) const;".format(RESULT, setter_name, value))
        definitions.append("{}<void> {}::{}(const {}& value) const {{ {} }}".format(
            RESULT, name, setter_name, value, body))
        return declarations, definitions

    def emit_component(self, component, name, used, references):
        """A component the class brings with it, typed as its own class. Read-only: the accessor
        names a component that already exists, not a slot to put a different one in."""
        referenced = self.classes_by_path.get(component.get("class", ""))
        if referenced is None:
            self.stats["components_omitted"] += 1
            return [], []
        accessor = snake(component["name"])
        if accessor in used:
            self.stats["components_shadowed"] += 1
            return [], []
        used.add(accessor)
        references.add(referenced["path"])
        self.stats["components"] += 1
        cls = self.path_of(referenced)
        return ["\t{} {}() const;".format(cls, accessor)], [
            "{} {}::{}() const {{ {}::note_origin<{}>(); return {}({}::ObjectRef::component("
            "object_.actor_name(), {}).with_class(::std::string({}::kPath))); }}".format(
                cls, name, accessor, RUNTIME, cls, cls, RUNTIME, cpp_str(component["name"]), cls)]

    def emit_function(self, function, name, used, references):
        """One callable function, as (declarations, definitions)."""
        if not function.get("callable") or not function.get("positional"):
            self.stats["functions_omitted"] += 1
            return [], []

        method = snake(function["name"])
        if method in used:
            # A property's accessor already took this name -- a property and its own Set<Name>
            # function both want `set_<name>`. They do the same thing.
            self.stats["functions_shadowed"] += 1
            return [], []

        mentioned = set()
        inputs, outputs, returns = [], [], None
        for parameter in function.get("parameters", []):
            direction = parameter.get("direction")
            try:
                cpp, how = self.cpp_type(parameter, mentioned)
                # A container of handles as an argument would need to say per element whether it
                # names an actor or a component; the runtime has no such argument.
                carryable = not (how == OBJECTS and direction == "in")
            except Unsupported:
                cpp, how, carryable = None, None, False

            if not carryable:
                if direction == "out":
                    # Dropped from the result and nothing else: the caller does not supply an out
                    # parameter, so one that cannot be carried back does not stop the call.
                    self.stats["out_params_dropped"] += 1
                    continue
                # An input the caller cannot pass, or a return value the method would have to
                # discard. Offering a method that silently drops its answer is worse than not
                # offering it -- omitted rather than loosely typed.
                self.stats["functions_omitted"] += 1
                return [], []

            entry = (snake(parameter["name"]), parameter["name"], cpp, how, parameter.get("kind"))
            if direction == "return":
                returns = entry
            elif direction == "out":
                outputs.append(entry)
            elif direction == "in":
                inputs.append(entry)

        if len({argument for argument, _, _, _, _ in inputs}) != len(inputs):
            self.stats["functions_omitted"] += 1
            return [], []

        used.add(method)
        references.update(mentioned)
        self.stats["functions"] += 1
        if outputs:
            self.stats["functions_with_out_params"] += 1

        signature = ", ".join("{} {}".format(self.parameter(cpp), argument)
                              for argument, _, cpp, _, _ in inputs)
        args = "{{{}}}".format(", ".join(
            "{}::{}({}, {})".format(
                RUNTIME,
                "argument_actor" if (how == OBJECT and kind == "actor")
                else "argument_component" if how == OBJECT
                else "argument",
                cpp_str(declared), argument)
            for argument, declared, _, how, kind in inputs))
        literal = cpp_str(function["name"])
        declarations = self.docs_for(function, "\t")

        if not outputs:
            result = "void" if returns is None else returns[2]
            call = "object_.call({}, {})".format(literal, args) if returns is None \
                else "object_.call_for<{}>({}, {})".format(result, literal, args)
            declarations.append("\t{}<{}> {}({}) const;".format(RESULT, result, method, signature))
            return declarations, ["{}<{}> {}::{}({}) const {{ return {}; }}".format(
                RESULT, result, name, method, signature, call)]

        # Out parameters, which is how a Blueprint usually hands back more than one thing. They come
        # back as a tuple with the return value first when there is one, then the out parameters in
        # declaration order -- but each is read by the name it was declared with, so adding a
        # parameter cannot silently shift the others onto the wrong values.
        wanted = ([returns] if returns else []) + outputs
        result = "::std::tuple<{}>".format(", ".join(cpp for _, _, cpp, _, _ in wanted))
        declarations.append("\t{}<{}> {}({}) const;".format(RESULT, result, method, signature))
        body = ["{}<{}> {}::{}({}) const {{".format(RESULT, result, name, method, signature),
                "\tauto response = object_.call_raw({}, {});".format(literal, args),
                "\tif (!response) return ::std::move(response).error();"]
        for index, (_, declared, cpp, _, _) in enumerate(wanted):
            body += ["\tauto r{} = {}::ObjectRef::result_of<{}>(response.value(), {});".format(
                         index, RUNTIME, cpp, cpp_str(declared)),
                     "\tif (!r{0}) return ::std::move(r{0}).error();".format(index)]
        body += ["\treturn {}({});".format(result, ", ".join(
                     "::std::move(r{}).value()".format(index) for index in range(len(wanted)))),
                 "}"]
        return declarations, ["\n".join(body)]

    # -- classes --------------------------------------------------------------------------------

    def emit_class(self, cls):
        """One class: (its header, its definitions, the classes its definitions need complete)."""
        name = ident(cls["name"])
        segments = module_for(cls["package"])
        base = self.classes_by_path.get(cls.get("super") or "")
        base_type = self.path_of(base) if base is not None else RUNTIME + "::Handle"

        # A Blueprint component variable is two things at once: a component template, and the object
        # property that holds it. Both would want the same accessor name; the component is the
        # useful one, so it is emitted first and the property stands down.
        used = set(HANDLE_MEMBERS) | {name}
        references = set()
        declarations, definitions = [], []
        for component in cls.get("components", []):
            d, b = self.emit_component(component, name, used, references)
            declarations += d
            definitions += b
        for member in cls.get("properties", []):
            if member.get("kind") == "struct":
                d, b = self.emit_struct_property(member, name, used)
            else:
                d, b = self.emit_property(member, name, used, references)
            declarations += d
            definitions += b
        for function in cls.get("functions", []):
            d, b = self.emit_function(function, name, used, references)
            declarations += d
            definitions += b
        references.discard(cls["path"])
        self.stats["classes"] += 1

        header = [GENERATED, "", "#pragma once", "", '#include "tempo/unreal.h"',
                  '#include "tempo/reflected/enums.h"', '#include "tempo/reflected/hierarchy.h"',
                  '#include "tempo/reflected/structs_fwd.h"']
        if base is not None:
            header.append('#include "{}"'.format(self.header_of(base)))
        header.append("")
        # Forward declarations: a method's declaration may name an incomplete class, and including
        # each one here would pull in every class reachable from this one.
        for path in sorted(references):
            other = self.classes_by_path[path]
            header.append("namespace tempo::reflected::classes::{} {{ class {}; }}".format(
                "::".join(module_for(other["package"])), ident(other["name"])))
        if references:
            header.append("")
        header += [
            "namespace tempo::reflected::classes::{} {{".format("::".join(segments)),
            "",
        ] + self.docs_for(cls, "") + [
            "class {} : public {} {{".format(name, base_type),
            "public:",
            "\tusing {}::{};".format(base_type, base_type.rsplit("::", 1)[1]),
            "",
            "\tstatic constexpr ::std::string_view kPath = {};".format(cpp_str(cls["path"])),
            "\tstatic const {}::Hierarchy& hierarchy() {{ return {}::hierarchy(); }}".format(
                RUNTIME, ROOT),
        ]
        if declarations:
            header.append("")
            header += declarations
        header += ["};", "", "}  // namespace tempo::reflected::classes::" + "::".join(segments), ""]
        return "\n".join(header), definitions, references

    def emit_classes(self):
        """Every class's header, the per-module headers, and the definition files.

        Returns ({include path: text}, {source path: text}).
        """
        headers, sources = {}, {}
        modules = dict(self.by_module)
        children = defaultdict(set)
        for segments in list(modules):
            for depth in range(1, len(segments)):
                children[segments[:depth]].add(segments[depth])
                modules.setdefault(segments[:depth], [])

        for segments, classes in sorted(modules.items()):
            names_seen = {}
            chunk, chunk_needs, chunks = [], set(), []
            for cls in sorted(classes, key=lambda c: c["path"]):
                name = ident(cls["name"])
                if name in names_seen:
                    # Two Blueprints in different folders can share a name. Rather than let one
                    # shadow the other, which would silently point a scenario at the wrong class, say so.
                    raise Exception(
                        "module {} has two classes named {}: {} and {}. Class names must be unique "
                        "within a module.".format("::".join(segments), name, names_seen[name],
                                                  cls["path"]))
                if name in children[segments]:
                    raise Exception("module {} has a class and a submodule both named {}".format(
                        "::".join(segments), name))
                names_seen[name] = cls["path"]
                text, definitions, references = self.emit_class(cls)
                headers[self.header_of(cls)] = text
                chunk.append((cls, definitions))
                chunk_needs |= references
                if len(chunk) >= 100:
                    chunks.append((chunk, chunk_needs))
                    chunk, chunk_needs = [], set()
            if chunk:
                chunks.append((chunk, chunk_needs))

            for index, (members, needs) in enumerate(chunks):
                includes = sorted({self.header_of(cls) for cls, _ in members}
                                  | {self.header_of(self.classes_by_path[p]) for p in needs})
                # Inside the namespace, naming each class unqualified: an out-of-line definition
                # spelled `::tempo::Result<bool> ::tempo::...::Widget::f()` reads as a member of
                # Result<bool>.
                namespace = "tempo::reflected::classes::" + "::".join(segments)
                lines = [GENERATED, ""] + ['#include "{}"'.format(i) for i in includes] + [
                    '#include "tempo/reflected/structs.h"', "", "namespace {} {{".format(namespace), ""]
                for _, definitions in members:
                    lines += definitions
                lines += ["", "}  // namespace " + namespace]
                sources["classes/{}_{}.cc".format("__".join(segments), index)] = "\n".join(lines) + "\n"

            umbrella = [GENERATED, "", "#pragma once", "", '#include "tempo/reflected/enums.h"',
                        '#include "tempo/reflected/structs.h"']
            umbrella += ['#include "{}"'.format(self.header_of(c))
                         for c in sorted(classes, key=lambda c: c["path"])]
            umbrella += ['#include "tempo/reflected/{}/{}.h"'.format("/".join(segments), child)
                         for child in sorted(children[segments])]
            headers["tempo/reflected/{}.h".format("/".join(segments))] = "\n".join(umbrella) + "\n"
        return headers, sources

    # -- enums ----------------------------------------------------------------------------------

    def emit_enums(self):
        """enums.h and enums.cc. An enum travels as its authored name rather than its numeric value,
        because that is what survives someone reordering the enumerators."""
        header = [GENERATED, "", "#pragma once", "", "#include <optional>", "#include <string_view>",
                  "", '#include "tempo/unreal.h"', "", "namespace tempo::reflected::enums {", ""]
        traits = ["namespace tempo::unreal {", ""]
        source = [GENERATED, "", '#include "tempo/reflected/enums.h"', "",
                  "namespace tempo::unreal {", ""]
        for enum in sorted(self.schema.get("enums", []), key=lambda e: e["name"]):
            self.stats["enums"] += 1
            name = ident(enum["name"])
            qualified = ROOT + "::enums::" + name
            members = enumerator_members(enum.get("enumerators", []), ident)
            header.append("enum class {} {{".format(name))
            header += ["\t{},".format(member) for member, _ in members]
            header += ["};", ""]
            traits += [
                "template <>",
                "struct EnumTraits<{}> {{".format(qualified),
                "\tstatic constexpr ::std::string_view kName = {};".format(cpp_str(enum["name"])),
                "\tstatic ::std::string_view name_of({} value);".format(qualified),
                "\tstatic ::std::optional<{}> from_name(::std::string_view name);".format(qualified),
                "};",
                "",
            ]
            source.append("::std::string_view EnumTraits<{}>::name_of({} value) {{".format(
                qualified, qualified))
            source.append("\tswitch (value) {")
            source += ["\t\tcase {}::{}: return {};".format(qualified, member, cpp_str(authored))
                       for member, authored in members]
            source += ["\t}", '\treturn "";', "}", ""]
            source.append("::std::optional<{}> EnumTraits<{}>::from_name(::std::string_view name) {{"
                          .format(qualified, qualified))
            source += ["\tif (name == {}) return {}::{};".format(cpp_str(authored), qualified, member)
                       for member, authored in members]
            source += ["\treturn ::std::nullopt;", "}", ""]
        header += ["}  // namespace tempo::reflected::enums", ""]
        traits += ["}  // namespace tempo::unreal", ""]
        source += ["}  // namespace tempo::unreal", ""]
        return "\n".join(header + traits), "\n".join(source)

    # -- structs --------------------------------------------------------------------------------

    def value_fields(self, struct, references):
        fields, used = [], set()
        for member in struct.get("members", []):
            try:
                cpp, how = self.cpp_type(member, references)
            except Unsupported:
                self.stats["struct_value_fields_omitted"] += 1
                continue
            if how == OBJECTS:
                # A container of handles needs per element what the builder cannot say. Leaving it
                # out is safe: a write is a merge, so the member keeps what the destination holds.
                self.stats["struct_value_fields_omitted"] += 1
                continue
            field = snake(member["name"])
            if field in used:
                self.stats["struct_value_fields_omitted"] += 1
                continue
            used.add(field)
            fields.append((field, member["name"], cpp, how, member.get("kind"), member))
        return fields

    def value_order(self):
        """The struct values in an order where each comes after those it holds by value."""
        order, placed, visiting = [], set(), set()

        def place(name):
            if name in placed or name in visiting:
                return
            visiting.add(name)
            for member in self.structs_by_name[name].get("members", []):
                # An array's element too, where that is not a cycle: an incomplete element type is
                # allowed in a std::vector, but a complete one is what nothing can trip over.
                held = member if member.get("kind") == "struct" else member.get("element") or {}
                if held.get("kind") == "struct" and held.get("struct") in self.expressible_structs:
                    place(held["struct"])
            visiting.discard(name)
            placed.add(name)
            order.append(name)

        for name in sorted(self.expressible_structs):
            place(name)
        return order

    def emit_structs(self):
        """structs_fwd.h, structs.h and structs.cc.

        Per struct, a proxy to reach into it by address, `<Name>Ref`, which is what a struct
        property's accessor returns, so a nested address like PostProcessSettings.BloomIntensity
        checks member by member. And when it travels whole, a value, `<Name>`, every member a
        std::optional, because a write is a merge and an unset member leaves the destination as it
        was.
        """
        structs = sorted(self.schema.get("structs", []), key=lambda s: s["name"])
        forward = [GENERATED, "", "#pragma once", "", "namespace tempo::reflected::structs {", ""]
        for struct in structs:
            forward.append("class {}Ref;".format(ident(struct["name"])))
            if struct["name"] in self.expressible_structs:
                forward.append("struct {};".format(ident(struct["name"])))
        forward += ["", "}  // namespace tempo::reflected::structs", ""]

        references = set()
        values, traits, source = [], ["namespace tempo::unreal {", ""], []
        for struct_name in self.value_order():
            struct = self.structs_by_name[struct_name]
            name = ident(struct_name)
            qualified = ROOT + "::structs::" + name
            fields = self.value_fields(struct, references)
            values += ["/// `{}` as a value. Unset members are not sent, so the destination keeps them."
                       .format(struct_name),
                       "struct {} {{".format(name)]
            values += ["\t::std::optional<{}> {};".format(cpp, field) for field, _, cpp, _, _, _ in fields]
            values += ["", "\tbool operator==(const {}&) const = default;".format(name), "};", ""]
            traits += [
                "template <>",
                "struct StructTraits<{}> {{".format(qualified),
                "\tstatic constexpr ::std::string_view kName = {};".format(cpp_str(struct_name)),
                "\tstatic {}<{}> from(const StructFields& fields);".format(RESULT, qualified),
                "\tstatic void to(const {}& value, StructBuilder& builder);".format(qualified),
                "};",
                "",
            ]
            source.append("{}<{}> StructTraits<{}>::from(const StructFields& fields) {{".format(
                RESULT, qualified, qualified))
            source.append("\t{} value;".format(qualified))
            for index, (field, declared, cpp, _, _, _) in enumerate(fields):
                source += ["\tauto f{} = fields.get<{}>({});".format(index, cpp, cpp_str(declared)),
                           "\tif (!f{0}) return ::std::move(f{0}).error();".format(index),
                           "\tvalue.{} = ::std::move(f{}).value();".format(field, index)]
            source += ["\treturn value;", "}", ""]
            source.append("void StructTraits<{}>::to(const {}& value, StructBuilder& builder) {{".format(
                qualified, qualified))
            if not fields:
                source.append("\t(void)value; (void)builder;")
            for field, declared, _, how, kind, _ in fields:
                method = "field" if how != OBJECT else ("actor" if kind == "actor" else "component")
                source.append("\tbuilder.{}({}, value.{});".format(method, cpp_str(declared), field))
            source += ["}", ""]
            self.stats["struct_values"] += 1
        traits += ["}  // namespace tempo::unreal", ""]

        proxies, proxy_source = [], []
        for struct in structs:
            name = ident(struct["name"])
            expressible = struct["name"] in self.expressible_structs
            proxy = name + "Ref"
            qualified_proxy = proxy
            used = {"load", "store", "ref_", proxy}
            body, body_source = [], []
            if expressible:
                body += ["\t{}<{}> load() const;".format(RESULT, name),
                         "\t{}<void> store(const {}& value) const;".format(RESULT, name)]
                body_source += [
                    "{}<{}::structs::{}> {}::load() const {{ return ref_.load<{}::structs::{}>(); }}"
                    .format(RESULT, ROOT, name, qualified_proxy, ROOT, name),
                    "{}<void> {}::store(const {}::structs::{}& value) const {{ return ref_.store(value); }}"
                    .format(RESULT, qualified_proxy, ROOT, name)]
            for member in struct.get("members", []):
                d, b = self.emit_struct_member(member, qualified_proxy, used, references)
                body += d
                body_source += b
            proxies += ["class {} {{".format(proxy), "public:",
                        "\texplicit {}({}::StructRef ref) : ref_(::std::move(ref)) {{}}".format(proxy, RUNTIME)]
            if body:
                proxies.append("")
                proxies += body
            proxies += ["", "private:", "\t{}::StructRef ref_;".format(RUNTIME), "};", ""]
            proxy_source += body_source
            self.stats["structs"] += 1

        # A struct value can hold a handle by value, so the classes it names are complete here.
        includes = sorted(self.header_of(self.classes_by_path[p]) for p in references)
        header = [GENERATED, "", "#pragma once", "", "#include <optional>", "#include <string>",
                  "#include <string_view>", "#include <vector>", "", '#include "tempo/unreal.h"',
                  '#include "tempo/reflected/enums.h"', '#include "tempo/reflected/structs_fwd.h"']
        header += ['#include "{}"'.format(i) for i in includes]
        header += ["", "namespace tempo::reflected::structs {", ""] + values + proxies
        header += ["}  // namespace tempo::reflected::structs", ""] + traits
        cc = [GENERATED, "", '#include "tempo/reflected/structs.h"', "",
              "namespace tempo::unreal {", ""] + source + ["}  // namespace tempo::unreal", ""]
        cc += ["namespace tempo::reflected::structs {", ""] + proxy_source + [
            "", "}  // namespace tempo::reflected::structs", ""]
        return "\n".join(forward), "\n".join(header), "\n".join(cc)

    def emit_struct_member(self, member, proxy, used, references):
        name = member["name"]
        accessor = snake(name)
        if accessor in used:
            return [], []
        literal = cpp_str(name)

        if member.get("kind") == "struct":
            nested = member.get("struct") or ""
            if nested not in self.struct_names:
                self.stats["struct_members_omitted"] += 1
                return [], []
            used.add(accessor)
            self.stats["struct_members"] += 1
            nested_proxy = "{}::structs::{}Ref".format(ROOT, ident(nested))
            return ["\t{} {}() const;".format(nested_proxy, accessor)], [
                "{} {}::{}() const {{ return {}(ref_.nested({})); }}".format(
                    nested_proxy, proxy, accessor, nested_proxy, literal)]

        try:
            cpp, how = self.cpp_type(member, references)
        except Unsupported:
            self.stats["struct_members_omitted"] += 1
            return [], []
        if how != PLAIN:
            # A struct member is addressed through StructRef, which carries the plain kinds.
            self.stats["struct_members_omitted"] += 1
            return [], []

        used.add(accessor)
        used.add("set_" + accessor)
        self.stats["struct_members"] += 1
        declarations = ["\t{}<{}> {}() const;".format(RESULT, cpp, accessor)]
        definitions = ["{}<{}> {}::{}() const {{ return ref_.get<{}>({}); }}".format(
            RESULT, cpp, proxy, accessor, cpp, literal)]
        if member.get("writable"):
            declarations.append("\t{}<void> set_{}({} value) const;".format(
                RESULT, accessor, self.parameter(cpp)))
            definitions.append("{}<void> {}::set_{}({} value) const {{ return ref_.set({}, value); }}"
                               .format(RESULT, proxy, accessor, self.parameter(cpp), literal))
        return declarations, definitions

    # -- assets ---------------------------------------------------------------------------------

    def emit_assets(self):
        """The asset catalog: one header per mount point, folders as namespaces, assets as
        `inline const AssetRef<Class>`.

        So a moved or renamed asset is a name that no longer resolves, and a material where a mesh is
        wanted does not compile. An asset is named by its package, which is unique within its folder.
        A folder whose namespace would share a name with an asset beside it takes a trailing
        underscore, as Python's does; two entries that still land on one name are both left out and
        counted, rather than failing the build.

        Returns {mount: text}, empty when the schema has no catalog.
        """
        tree = {}
        for asset in self.schema.get("assets", []):
            segments = asset["path"].split(".", 1)[0].strip("/").split("/")
            if len(segments) < 2:
                self.stats["assets_unplaceable"] += 1
                continue
            node = tree.setdefault(segments[0], {"folders": {}, "assets": {}})
            for folder in segments[1:-1]:
                node = node["folders"].setdefault(folder, {"folders": {}, "assets": {}})
            node["assets"].setdefault(segments[-1], []).append(asset)

        def emit(node, indent, includes):
            lines = []
            variables, namespaces = defaultdict(list), defaultdict(list)
            for name, assets in node["assets"].items():
                variables[ident(name)].append(assets)
            for folder in node["folders"]:
                namespaces[snake(folder)].append(folder)
            for name in sorted(namespaces):
                if len(namespaces[name]) > 1:
                    self.stats["assets_colliding"] += 1
                    continue
                spelled = name + "_" if name in variables else name
                lines.append("{}namespace {} {{".format(indent, spelled))
                lines += emit(node["folders"][namespaces[name][0]], indent + "\t", includes)
                lines.append("{}}}".format(indent))
            for name in sorted(variables):
                if len(variables[name]) > 1 or len(variables[name][0]) > 1:
                    self.stats["assets_colliding"] += 1
                    continue
                asset = variables[name][0][0]
                referenced = self.classes_by_path.get(asset["class"])
                if referenced is not None:
                    # Complete here, so that converting to a superclass's AssetRef can check it is one.
                    includes.add(self.header_of(referenced))
                asset_type = "{}::AssetRef<{}>".format(RUNTIME, self.path_of(referenced)) \
                    if referenced else RUNTIME + "::AssetRef<>"
                lines.append("{}inline const {} {}{{{}}};".format(
                    indent, asset_type, name, cpp_str(asset["path"])))
                self.stats["assets"] += 1
            return lines

        mounts = {}
        for mount, node in sorted(tree.items()):
            includes = set()
            body = emit(node, "", includes)
            namespace = "tempo::reflected::assets::" + snake(mount)
            mounts[snake(mount)] = "\n".join(
                [GENERATED, "", "#pragma once", "", '#include "tempo/unreal.h"']
                + ['#include "{}"'.format(i) for i in sorted(includes)]
                + ["", "namespace {} {{".format(namespace), ""] + body
                + ["", "}  // namespace " + namespace, ""])
        return mounts

    # -- hierarchy ------------------------------------------------------------------------------

    def emit_hierarchy(self):
        """The one table that has to be data rather than code: who derives from whom, and what each
        entry hashed to in the build these classes came from, for world::check_schema."""
        def table(name, entries):
            lines = ["constexpr ::std::array<HashEntry, {}> {} = {{{{".format(len(entries), name)]
            lines += ["\t{{{}, {}}},".format(cpp_str(key), cpp_str(value)) for key, value in entries]
            return lines + ["}};", ""]

        pairs = sorted((cls["path"], cls.get("super") or "") for cls in self.schema["classes"]
                       if cls.get("super"))
        lines = [GENERATED, "", "#include <algorithm>", "#include <array>", "",
                 '#include "tempo/reflected/hierarchy.h"', "", "namespace tempo::reflected {", "",
                 "namespace {", "", "using ::tempo::unreal::HashEntry;", "",
                 "// Each class and the one it derives from, sorted by path so a lookup can bisect."]
        lines += table("kSuperclass", pairs)
        lines.append("// Per entry and not just the header's one number: a whole-walk hash says only "
                     "that something moved.")
        for name, kind, key, value in (
                ("kClassHash", "classes", "path", "content_hash"),
                ("kStructHash", "structs", "name", "content_hash"),
                ("kEnumHash", "enums", "name", "content_hash"),
                # An asset's identity is its path and class, so its class is what is compared.
                ("kAssetHash", "assets", "path", "class")):
            entries = sorted((entry[key], entry.get(value, "")) for entry in self.schema.get(kind, []))
            lines += table(name, entries)
        header = self.schema["header"]
        lines += [
            "::std::optional<::std::string_view> lookup(::std::span<const HashEntry> entries, "
            "::std::string_view key) {",
            "\tauto found = ::std::lower_bound(entries.begin(), entries.end(), key,",
            "\t\t[](const HashEntry& entry, ::std::string_view wanted) { return entry.first < wanted; });",
            "\tif (found == entries.end() || found->first != key) return ::std::nullopt;",
            "\treturn found->second;",
            "}",
            "",
            "class Table final : public ::tempo::unreal::Hierarchy {",
            "public:",
            "\t::std::optional<::std::string_view> superclass(::std::string_view class_path) const override {",
            "\t\treturn lookup(kSuperclass, class_path);",
            "\t}",
            "",
            "\t::tempo::unreal::SchemaIdentity header() const override {",
            "\t\treturn {{{}, {}, {}}};".format(
                cpp_str(str(header.get("schema_version", ""))),
                cpp_str(str(header.get("engine_version", ""))),
                cpp_str(str(header.get("content_hash", "")))),
            "\t}",
            "",
            "\t::std::span<const HashEntry> hashes(::tempo::unreal::EntryKind kind) const override {",
            "\t\tswitch (kind) {",
            "\t\t\tcase ::tempo::unreal::EntryKind::Class: return kClassHash;",
            "\t\t\tcase ::tempo::unreal::EntryKind::Struct: return kStructHash;",
            "\t\t\tcase ::tempo::unreal::EntryKind::Enum: return kEnumHash;",
            "\t\t\tcase ::tempo::unreal::EntryKind::Asset: return kAssetHash;",
            "\t\t}",
            "\t\treturn {};",
            "\t}",
            "};",
            "",
            "}  // namespace",
            "",
            "const ::tempo::unreal::Hierarchy& hierarchy() {",
            "\tstatic const Table table;",
            "\treturn table;",
            "}",
            "",
            "}  // namespace tempo::reflected",
            "",
        ]
        return "\n".join(lines)


