"""Mount a sensor rig on a vehicle, configured through the reflected API.

The reflected API (``city_sample.reflected``, generated by Package.sh for exactly this build) gives
every Unreal class a typed Python class, so ``lidar.HorizontalBeams = 1024`` is a checked write: if
a Tempo release renames, retypes or removes that property, Pyright flags this file before anything
runs. That is why the JSON is applied by the explicit ``apply_*`` functions below rather than by
looping ``setattr`` over the JSON's keys -- a loop would type-check against anything.

Units: the reflected API speaks Unreal's own units (centimeters, degrees). The JSON speaks meters
and degrees. Lengths are the only thing converted, and only here. Component placement goes through
``world.add_component``, which like the rest of ``tempo_sim.world`` is SI and right-handed.
"""

import math
from dataclasses import dataclass, field
from typing import Dict, List, Tuple

from tempo_sim import world
from tempo_sim.unreal import FIntPoint, FVector2D

import city_sample.reflected  # noqa: F401  (importing registers the generated classes)
from city_sample.reflected.Engine import Actor
from city_sample.reflected.TempoSensors import TempoCamera, TempoLidar, TempoSceneCaptureComponent2D
from city_sample.reflected.enums import ETempoLensModel
from city_sample.reflected.structs import FLidarBeamCalibration, FTempoLensParameters

import tempo_sim.tempo_world as tw
import tempo_sim.TempoSensors.Sensors_pb2 as Sensors

from tempo_rerun.sensors import SensorInfo

from .config import CameraConfig, LidarConfig, RigConfig, SensorConfig

CM_PER_M = 100.0

CAMERA_MEASUREMENTS = {int(m) for m in (Sensors.MT_COLOR_IMAGE, Sensors.MT_DEPTH_IMAGE,
                                         Sensors.MT_LABEL_IMAGE, Sensors.MT_BOUNDING_BOXES,
                                         Sensors.MT_VIDEO)}


# -- the reflected-API writes -------------------------------------------------------------------

def apply_camera(camera: TempoCamera, cfg: CameraConfig) -> None:
    """Write a CameraConfig to a TempoCamera. Call inside ``world.batch()`` so the camera
    reconfigures once, not once per property."""
    k = list(cfg.lens.k) + [0.0] * (6 - len(cfg.lens.k))
    camera.RateHz = cfg.rate_hz
    camera.SizeXY = FIntPoint(X=cfg.resolution[0], Y=cfg.resolution[1])
    camera.FOVAngle = cfg.fov_deg                                  # degrees, horizontal
    camera.LensParameters = FTempoLensParameters(
        LensModel=ETempoLensModel(cfg.lens.model),
        K1=k[0], K2=k[1], K3=k[2], K4=k[3], K5=k[4], K6=k[5],
        Xi=cfg.lens.xi, Alpha=cfg.lens.alpha,
        PrincipalPoint=FVector2D(X=cfg.lens.principal_point[0], Y=cfg.lens.principal_point[1]),
    )
    camera.UpsamplingFactor = cfg.upsampling_factor
    camera.bEnableScreenPercentage = cfg.screen_percentage is not None
    if cfg.screen_percentage is not None:
        camera.ScreenPercentage = cfg.screen_percentage
    _apply_passthrough(camera, cfg.unreal_properties)


def apply_lidar(lidar: TempoLidar, cfg: LidarConfig) -> None:
    """Write a LidarConfig to a TempoLidar. Call inside ``world.batch()``."""
    lidar.RateHz = cfg.rate_hz
    lidar.HorizontalBeams = cfg.horizontal_beams
    lidar.HorizontalFOV = cfg.horizontal_fov_deg                   # degrees
    lidar.MinDistance = cfg.range_m[0] * CM_PER_M                  # cm
    lidar.MaxDistance = cfg.range_m[1] * CM_PER_M                  # cm
    if cfg.elevations_deg:
        # A beam pattern replaces the uniform VerticalBeams x VerticalFOV grid.
        lidar.VerticalBeams = len(cfg.elevations_deg)
        lidar.BeamCalibration = [FLidarBeamCalibration(ElevationDeg=e, AzimuthOffsetDeg=0.0)
                                 for e in cfg.elevations_deg]
    else:
        lidar.BeamCalibration = []
        lidar.VerticalBeams = cfg.vertical_beams
        lidar.VerticalFOV = cfg.vertical_fov_deg                   # degrees
    lidar.bSimulateParticipatingMedia = cfg.participating_media
    _apply_passthrough(lidar, cfg.unreal_properties)


def _apply_passthrough(component, properties: Dict[str, object]) -> None:
    """The JSON's ``unreal_properties`` escape hatch: raw Unreal property names and native units.
    Untyped by design -- a type checker cannot see these, which is the trade the JSON makes."""
    for name, value in properties.items():
        setattr(component, name, value)


# -- placement ----------------------------------------------------------------------------------

def anchors_from_bounds(local_bounds) -> Dict[str, Tuple[float, float, float]]:
    """Mount points from the vehicle's local bounding box (meters, x forward, y left, z up)."""
    lo, hi = local_bounds.min, local_bounds.max
    cx, cy = (lo.x + hi.x) * 0.5, (lo.y + hi.y) * 0.5
    bumper_z = lo.z + 0.35 * (hi.z - lo.z)
    return {
        "origin": (0.0, 0.0, 0.0),
        "roof_center": (cx, cy, hi.z),
        # The front of the box at roof height: ahead of the roof, so a forward camera there sees
        # the road rather than a van's long flat roof.
        "front_top": (hi.x, cy, hi.z),
        "front_bumper": (hi.x, cy, bumper_z),
        "rear_bumper": (lo.x, cy, bumper_z),
    }


def _transform(position, rpy_deg) -> world.Transform:
    r, p, y = (math.radians(a) for a in rpy_deg)
    return world.Transform(location=world.Vector(x=position[0], y=position[1], z=position[2]),
                           rotation=world.Rotation(r=r, p=p, y=y))


@dataclass
class MountedSensor:
    name: str
    config: SensorConfig
    position_m: Tuple[float, float, float]
    rpy_deg: Tuple[float, float, float]
    info: SensorInfo

    def calibration(self) -> dict:
        """Extrinsics in the vehicle frame and intrinsics, for the recorder's calib files."""
        cfg = self.config
        out = {"sensor": self.name, "frame": "vehicle (x forward, y left, z up; meters; right-handed)",
               "position_m": list(self.position_m), "rpy_deg": list(self.rpy_deg)}
        if isinstance(cfg, CameraConfig):
            out.update(type="camera", resolution=list(cfg.resolution), fov_deg=cfg.fov_deg,
                       rate_hz=cfg.rate_hz, lens=dict(model=cfg.lens.model, k=list(cfg.lens.k),
                                                      xi=cfg.lens.xi, alpha=cfg.lens.alpha,
                                                      principal_point=list(cfg.lens.principal_point)))
            if cfg.lens.model == "Pinhole":
                fx = cfg.resolution[0] * 0.5 / math.tan(math.radians(cfg.fov_deg) * 0.5)
                out["K"] = [[fx, 0, cfg.resolution[0] * 0.5], [0, fx, cfg.resolution[1] * 0.5], [0, 0, 1]]
        else:
            out.update(type="lidar", rate_hz=cfg.rate_hz, horizontal_beams=cfg.horizontal_beams,
                       horizontal_fov_deg=cfg.horizontal_fov_deg, range_m=list(cfg.range_m),
                       vertical_beams=cfg.vertical_beams, vertical_fov_deg=cfg.vertical_fov_deg,
                       elevations_deg=list(cfg.elevations_deg))
        return out


@dataclass
class MountedRig:
    rig: RigConfig
    owner: str
    sensors: List[MountedSensor] = field(default_factory=list)

    @property
    def infos(self) -> List[SensorInfo]:
        return [s.info for s in self.sensors]


async def mount_rig(vehicle: Actor, rig: RigConfig, *, with_bboxes: bool = False) -> MountedRig:
    """Add the rig's sensors to `vehicle` and configure them. Idempotent: sensors of the same name
    left by an earlier mount on this vehicle are replaced, not duplicated."""
    state = await tw.get_current_actor_state(actor=vehicle.actor)
    anchors = anchors_from_bounds(state.local_bounds)

    wanted = {m.name for m in rig.mounts}
    for existing in await world.get_components_async(vehicle, TempoSceneCaptureComponent2D):
        if existing.component in wanted:
            await world.destroy_component_async(existing)

    mounted = MountedRig(rig=rig, owner=vehicle.actor)
    handles = []
    for mount in rig.mounts:
        ax, ay, az = anchors[mount.anchor]
        position = (ax + mount.offset_m[0], ay + mount.offset_m[1], az + mount.offset_m[2])
        cls = TempoCamera if isinstance(mount.sensor, CameraConfig) else TempoLidar
        handle = await world.add_component_async(cls, vehicle, name=mount.name,
                                                 transform=_transform(position, mount.rpy_deg))
        handles.append((handle, mount))

        if isinstance(mount.sensor, CameraConfig):
            measurements = set(CAMERA_MEASUREMENTS)
            if not with_bboxes:
                measurements.discard(int(Sensors.MT_BOUNDING_BOXES))
            # An ideal pinhole frustum is only right for a pinhole lens; leave fisheyes 2D-only.
            fov = mount.sensor.fov_deg if mount.sensor.lens.model == "Pinhole" else None
        else:
            measurements, fov = {int(Sensors.MT_LIDAR_SCAN)}, None
        mounted.sensors.append(MountedSensor(
            name=handle.component, config=mount.sensor, position_m=position, rpy_deg=mount.rpy_deg,
            info=SensorInfo(owner=vehicle.actor, name=handle.component, rate_hz=mount.sensor.rate_hz,
                            measurement_types=measurements, fov_deg=fov)))

    # One RunBatch for every sensor's properties: the server applies a batch between two ticks, so
    # no sensor captures half-configured, and each reconfigures once.
    async with world.batch():
        for handle, mount in handles:
            if isinstance(handle, TempoCamera):
                apply_camera(handle, mount.sensor)
            elif isinstance(handle, TempoLidar):
                apply_lidar(handle, mount.sensor)
    return mounted
